class Exercise {
  final String topic;
  final String sentence;
  final List<String> options;
  final int answer; // индекс правильного варианта
  final String why;

  const Exercise(this.topic, this.sentence, this.options, this.answer, this.why);

  /// Проверяет упражнение от ИИ; возвращает null, если формат неверен.
  static Exercise? fromJson(Map<String, dynamic> j) {
    final topic = j['topic']?.toString() ?? '';
    final opts = (j['options'] as List?)?.map((e) => e.toString()).toList() ?? <String>[];
    final ans = j['answer'];
    if (!grammarTopics.any((t) => t.id == topic)) return null;
    if (opts.length < 2 || ans is! int || ans < 0 || ans >= opts.length) return null;
    final sentence = j['sentence']?.toString() ?? '';
    if (!sentence.contains('___')) return null;
    return Exercise(topic, sentence, opts, ans, (j['why'] ?? '').toString());
  }
}

